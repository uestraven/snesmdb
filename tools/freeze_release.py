#!/usr/bin/env python3
"""Pin a published corpus so an evaluation names one exact artifact.

    freeze_release.py <dist-dir> [--label rc1]
    freeze_release.py <dist-dir> --verify

Writes `RELEASE.json` into the tree: the commit that built it, the corpus
counts it claims, and a SHA-256 for every published file. `--verify` re-reads
the tree and reports every file that changed, appeared or went missing.

WHY THIS EXISTS. An independent evaluation is only evidence if everyone can
say which bytes were evaluated. Without a freeze, a corpus is whatever the
last `make corpus` produced, so a disagreement between the evaluator's number
and ours cannot be separated into "they read it differently" and "they read
something else". That distinction is the whole value of the exercise.

It also catches the quieter failure: a tree that was rebuilt mid-evaluation.
`provenance.json` records the commit but says nothing about whether the files
still match it, because the publish could have been interrupted or a file
touched afterwards.

This writes INSIDE the published tree, which is outside the repository by
construction -- the corpus is derived from research-only SPCs and must never
be committed. The directory is refused if it is inside a git work tree.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from snesmdb import corpus as corpus_mod, provenance as provenance_mod  # noqa: E402

SCHEMA = "snesmdb.release.v1"

#: The name of the pin itself, excluded from the hashes it contains.
RELEASE_FILE = "RELEASE.json"

#: Every pin ever written to a tree is also kept here under its label, so
#: superseding a candidate does not destroy the record of what the previous
#: one contained. Excluded from the hashes for the same reason as the pin.
RELEASE_DIR = "releases"

#: Read in chunks: the tree is a few gigabytes and a release should not need
#: to hold a file in memory to hash it.
CHUNK = 1 << 20


def _inside_git(path: Path) -> bool:
    done = subprocess.run(
        ["git", "-C", str(path), "rev-parse", "--is-inside-work-tree"],
        capture_output=True, text=True,
    )
    return done.returncode == 0 and done.stdout.strip() == "true"


def digest(path: Path) -> str:
    out = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(CHUNK), b""):
            out.update(block)
    return out.hexdigest()


def inventory(dist: Path) -> dict[str, dict[str, Any]]:
    """Every published file, by tree-relative path."""
    found: dict[str, dict[str, Any]] = {}
    for path in sorted(dist.rglob("*")):
        if not path.is_file() or path.name == RELEASE_FILE:
            continue
        key = path.relative_to(dist).as_posix()
        # GENERATED BYTECODE IS NOT PUBLISHED DATA.
        #
        # Running the packaged toolkit writes `__pycache__` into the
        # archive, so a researcher who used the release and then verified
        # its integrity was told "this is NOT the frozen artifact" -- an
        # alarming false positive produced by nothing but ordinary use.
        # Bytecode is excluded from the pin and from the comparison, so
        # verification is stable across use and across interpreters.
        if "__pycache__" in path.parts or path.suffix in (".pyc", ".pyo"):
            continue
        # The pin archive is metadata about releases, not published data; a
        # new pin would otherwise change the tree it is pinning.
        if key.startswith(f"{RELEASE_DIR}/"):
            continue
        found[key] = {"sha256": digest(path), "bytes": path.stat().st_size}
    return found


def _build_provenance(dist: Path) -> dict[str, Any]:
    """What the tree records about its own construction.

    Read from `provenance.json` in the tree, because that is the only record
    of the commit the corpus was actually published from. The checkout at
    freeze time is a different thing and must not be substituted for it.
    """
    path = dist / "provenance.json"
    if not path.is_file():
        return {}
    try:
        record = json.loads(path.read_text())
    except (OSError, ValueError):
        return {}
    return {
        key: record.get(key)
        for key in ("git_commit", "git_branch", "built_utc", "dirty")
    }


def build(dist: Path, label: str) -> dict[str, Any]:
    index_path = dist / "index.json"
    if not index_path.is_file():
        raise SystemExit(f"no index.json in {dist}; nothing to freeze")
    raw = json.loads(index_path.read_text())
    files = inventory(dist)
    return {
        "schema": SCHEMA,
        "label": label,
        "frozen_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        # The index's own claims, copied so a mismatch between what the
        # corpus says about itself and what it contains is visible here.
        "index_schema": raw.get("schema") if isinstance(raw, dict) else None,
        "formats": raw.get("formats", {}) if isinstance(raw, dict) else {},
        "corpus": raw.get("corpus", {}) if isinstance(raw, dict) else {},
        "n_tracks_in_index": len(corpus_mod.tracks_of(raw)),
        "n_files": len(files),
        "total_bytes": sum(f["bytes"] for f in files.values()),
        # PROVENANCE OF THE FREEZE, which is not provenance of the build.
        # This field was called `built_by`, and it was read as naming the
        # commit that produced the corpus. It does not: freezing happens
        # later, often after further commits. The two coincided for the first
        # release and the mislabelling was invisible; by the second, the pin
        # named a commit three commits after the one that built the tree.
        "frozen_by": provenance_mod.record(tool="freeze_release.py"),
        # Provenance of the BUILD, taken from the tree's own record rather
        # than from the current checkout. This is the commit to return to in
        # order to reproduce these bytes.
        "built_from": _build_provenance(dist),
        "files": files,
    }


def verify(dist: Path) -> int:
    """Differences between the pin and the tree. Exit code is the count."""
    path = dist / RELEASE_FILE
    if not path.is_file():
        raise SystemExit(f"no {RELEASE_FILE} in {dist}; nothing to verify")
    pinned = json.loads(path.read_text())
    recorded: dict[str, dict[str, Any]] = pinned.get("files", {})
    current = inventory(dist)

    changed = sorted(
        key for key in recorded.keys() & current.keys()
        if recorded[key]["sha256"] != current[key]["sha256"]
    )
    missing = sorted(recorded.keys() - current.keys())
    added = sorted(current.keys() - recorded.keys())

    print(f"release {pinned.get('label')} frozen {pinned.get('frozen_utc')}")
    print(f"  built from  {pinned.get('built_from', {}).get('git_commit')}")
    print(f"  frozen at   {pinned.get('frozen_by', {}).get('git_commit')}")
    print(f"  files       {len(recorded)} pinned, {len(current)} present")
    for label, group in (
        ("CHANGED", changed), ("MISSING", missing), ("ADDED", added),
    ):
        for key in group[:20]:
            print(f"  {label:8} {key}")
        if len(group) > 20:
            print(f"  {label:8} ... and {len(group) - 20} more")

    total = len(changed) + len(missing) + len(added)
    if not total:
        print("\nintact: every pinned file is present and unchanged")
    else:
        print(f"\n{total} difference(s): this is NOT the frozen artifact")
    return total


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("dist_dir", type=Path)
    parser.add_argument("--label", default="rc1")
    parser.add_argument(
        "--verify", action="store_true",
        help="re-hash the tree and report differences from the pin",
    )
    parser.add_argument(
        "--replace", action="store_true",
        help="supersede a pin that carries a different label",
    )
    parser.add_argument(
        "--allow-dirty", action="store_true",
        help="freeze even though the working tree has uncommitted changes. "
             "Refused by default: a pin naming a commit that does not "
             "contain the code which built the tree cannot be reproduced, "
             "which is the one thing a release candidate has to offer.",
    )
    args = parser.parse_args()

    dist = args.dist_dir.expanduser().resolve()
    if not dist.is_dir():
        raise SystemExit(f"{dist} is not a directory")
    if _inside_git(dist):
        raise SystemExit(
            f"{dist} is inside a git work tree. The corpus is derived from "
            f"research-only SPCs and must not be committed."
        )

    if args.verify:
        raise SystemExit(min(verify(dist), 125))

    pin = build(dist, args.label)
    built = pin["frozen_by"]
    if built.get("dirty") and not args.allow_dirty:
        raise SystemExit(
            f"refusing to freeze: the working tree has uncommitted changes, "
            f"so commit {built.get('git_commit')} does not describe the code "
            f"that built this corpus.\n"
            f"  dirty: {', '.join(built.get('dirty_paths') or [])[:300]}\n"
            f"Commit first, or pass --allow-dirty for a throwaway pin."
        )
    # AND THE TREE'S OWN BUILD MUST HAVE BEEN CLEAN. The check above looks at
    # the checkout as it is NOW, which says nothing about the checkout the
    # corpus was published from. A tree built from uncommitted changes and
    # frozen after committing them passes the first check and is still not
    # reproducible from any commit -- which happened: gate5-rc3 was first
    # published from 15 modified files, and only the pin's own `built_from`
    # record showed it.
    origin = pin.get("built_from") or {}
    if origin.get("dirty") and not args.allow_dirty:
        raise SystemExit(
            f"refusing to freeze: this corpus was PUBLISHED from a dirty "
            f"working tree (commit {str(origin.get('git_commit'))[:12]}, "
            f"built {origin.get('built_utc')}), so its bytes cannot be "
            f"reproduced from any commit.\n"
            f"Re-publish from a clean checkout, or pass --allow-dirty for a "
            f"throwaway pin."
        )
    archive = dist / RELEASE_DIR
    archive.mkdir(exist_ok=True)

    # Superseding a candidate must be deliberate. An evaluation in progress
    # names a label, and silently repointing that label at a different tree
    # would invalidate the evaluation without leaving a trace.
    #
    # The outgoing pin is archived BEFORE the refusal is raised, so the
    # promise in that message is already true when it is printed. An earlier
    # version archived only the incoming pin while telling the operator the
    # old one was kept, so `--replace` would have destroyed exactly the record
    # the message said it preserved.
    existing = dist / RELEASE_FILE
    if existing.is_file():
        outgoing = json.loads(existing.read_text())
        previous = outgoing.get("label")
        if previous:
            kept = archive / f"{previous}.json"
            if not kept.is_file():
                kept.write_text(json.dumps(outgoing, indent=1))
        if previous != args.label and not args.replace:
            raise SystemExit(
                f"this tree is already pinned as {previous!r}. Writing "
                f"{args.label!r} over it would supersede the candidate an "
                f"evaluation may be using.\nPass --replace to proceed; the old "
                f"pin has been archived to {RELEASE_DIR}/{previous}.json."
            )
    (archive / f"{args.label}.json").write_text(json.dumps(pin, indent=1))
    (dist / RELEASE_FILE).write_text(json.dumps(pin, indent=1))
    print(f"froze {pin['n_files']} files, {pin['total_bytes'] / 1e9:.2f} GB")
    print(f"  label       {pin['label']}")
    print(f"  built from  {(pin.get('built_from') or {}).get('git_commit')}")
    print(f"  frozen at   {pin['frozen_by'].get('git_commit')}")
    print(f"  dirty       {pin['frozen_by'].get('dirty')}")
    print(f"  index       {pin['index_schema']}")
    print(f"  tracks      {pin['n_tracks_in_index']}")
    print(f"  wrote       {dist / RELEASE_FILE}")


if __name__ == "__main__":
    main()
